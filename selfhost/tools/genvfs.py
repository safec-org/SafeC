#!/usr/bin/env python3
"""Embeds selfhost/include/** and selfhost/runtime/rt.sc into src/vfs.sc."""
import os, re, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
files = [("<runtime>", os.path.join(root, "runtime", "rt.sc"))]
inc = os.path.join(root, "include")
for d, _, fs in sorted(os.walk(inc)):
    for f in sorted(fs):
        p = os.path.join(d, f)
        files.append((os.path.relpath(p, inc).replace(os.sep, "/"), p))

# The SafeC std library bundled for programs: the headers in STD_SEED and
# everything they include, served as "std/<path>". A header's implementation
# (the .sc file next to it) is compiled into the same translation unit: the
# header text ends with an #include of it. Where stdshim/<header>.sc exists
# it is appended instead, as the playground implementation (for std code
# that needs an OS or libc pieces the scc runtime doesn't have).
STD_SEED = [
    "io.h", "str.h", "mem.h", "panic.h", "math.h", "fmt.h", "convert.h",
    "collections/slice.h", "collections/vec.h", "collections/string.h",
    "collections/map.h", "stdint.h", "limits.h", "float.h", "stdbool.h",
    "inttypes.h", "ctype.h", "assert.h", "stdckdint.h", "cmp.h", "traits.h",
    "bit.h", "result.h", "atomic.h", "sys.h",
]
std_root = os.path.join(os.path.dirname(root), "std")
shim_root = os.path.join(root, "stdshim")
std_order = []
def std_visit(p):
    if p in std_order:
        return
    full = os.path.join(std_root, p)
    if not os.path.exists(full):
        return
    std_order.append(p)
    with open(full, encoding="utf-8") as fh:
        text = fh.read()
    for m in re.finditer(r"#include\s*<std/([^>]+)>", text):
        std_visit(m.group(1))
    if p.endswith(".h") and not os.path.exists(os.path.join(shim_root, p + ".sc")):
        if os.path.exists(os.path.join(std_root, p[:-2] + ".sc")):
            std_visit(p[:-2] + ".sc")
for h in STD_SEED:
    std_visit(h)
std_files = [("std/" + p, os.path.join(std_root, p)) for p in std_order]

def lit(s):
    out = []
    for line in s.splitlines(True):
        e = line.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "\\t").replace("\n", "\\n")
        out.append('    "' + e + '"')
    return "\n".join(out) if out else '    ""'

o = ["// vfs.sc — GENERATED by tools/genvfs.py from include/ and runtime/: do not edit.",
     '#include "scc.h"', '#include "driver.h"', "",
     "int g_vfs_file[%d];" % (len(files) + len(std_files) + 1), ""]
files += std_files
for i, (name, path) in enumerate(files):
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    if name.startswith("std/") and name.endswith(".h"):
        shim = os.path.join(shim_root, name[4:] + ".sc")
        impl = name[:-2] + ".sc"
        if os.path.exists(shim):
            with open(shim, encoding="utf-8") as fh:
                text += "\n" + fh.read()
        elif impl[4:] in std_order:
            text += "\n#pragma scc_impl <" + impl + ">\n"
    o.append("const char* g_vfs_%d() {\n    return\n%s;\n}\n" % (i, lit(text)))
o.append("int vfs_add(int name, const char* text) {")
o.append("    int n = lit_len(text);")
o.append("    int start = g_src_len;")
o.append("    int i = 0;")
o.append("    while (i < n && g_src_len < SRC_MAX) { g_src[g_src_len] = (unsigned char)lit_char(text, i); g_src_len = g_src_len + 1; i = i + 1; }")
o.append("    return add_file(name, start, n);")
o.append("}\n")
o.append("int vfs_load(int name) {")
for i, (name, _) in enumerate(files):
    o.append('    if (str_eq_lit(name, "%s") == 1) {' % name)
    o.append("        if (g_vfs_file[%d] == 0) { g_vfs_file[%d] = vfs_add(name, g_vfs_%d()); }" % (i, i, i))
    o.append("        return g_vfs_file[%d];" % i)
    o.append("    }")
o.append("    return 0;")
o.append("}")
with open(os.path.join(root, "src", "vfs.sc"), "w") as fh:
    fh.write("\n".join(o) + "\n")
