#!/usr/bin/env python3
"""Embeds selfhost/include/** and selfhost/runtime/rt.sc into src/vfs.sc."""
import os, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
files = [("<runtime>", os.path.join(root, "runtime", "rt.sc"))]
inc = os.path.join(root, "include")
for d, _, fs in sorted(os.walk(inc)):
    for f in sorted(fs):
        p = os.path.join(d, f)
        files.append((os.path.relpath(p, inc).replace(os.sep, "/"), p))

def lit(s):
    out = []
    for line in s.splitlines(True):
        e = line.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "\\t").replace("\n", "\\n")
        out.append('    "' + e + '"')
    return "\n".join(out) if out else '    ""'

o = ["// vfs.sc — GENERATED by tools/genvfs.py from include/ and runtime/: do not edit.",
     '#include "scc.h"', '#include "driver.h"', "",
     "int g_vfs_file[64];", ""]
for i, (name, path) in enumerate(files):
    with open(path, encoding="utf-8") as fh:
        o.append("const char* g_vfs_%d() {\n    return\n%s;\n}\n" % (i, lit(fh.read())))
o.append("int vfs_add(int name, const char* text) {")
o.append("    int n = lit_len(text);")
o.append("    int start = g_src_len;")
o.append("    int i = 0;")
o.append("    while (i < n && g_src_len < SRC_MAX) { g_src[g_src_len] = (unsigned char)lit_char(text, i); g_src_len = g_src_len + 1; i = i + 1; }")
o.append("    return add_file(name, start, n);")
o.append("}\n")
o.append("int vfs_load(int name) {")
for i, (name, _) in enumerate(files):
    o.append('    if (str_eq_lit(name, "%s") == 1) {' % name)
    o.append("        if (g_vfs_file[%d] == 0) { g_vfs_file[%d] = vfs_add(name, g_vfs_%d()); }" % (i, i, i))
    o.append("        return g_vfs_file[%d];" % i)
    o.append("    }")
o.append("    return 0;")
o.append("}")
with open(os.path.join(root, "src", "vfs.sc"), "w") as fh:
    fh.write("\n".join(o) + "\n")
