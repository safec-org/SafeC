#!/bin/sh
# Regenerates device_kernels_wgsl.h (device_kernels.wgsl as a string, and
# which entry point runs each DK_* kernel) and checks the WGSL kernels against
# device_kernels.cu: every DK_KERNEL there needs its entry point here (its own
# name, or dk_ew with the pipeline constant OPC for dk_ewop_<op>), no entry
# point may name a kernel device_kernels.cu lacks, and the EW_* / OPT_* codes
# must agree. The ids are device_kernels.h's (both scripts number the
# DK_KERNELs of device_kernels.cu in order). Run after editing either file;
# the generated header is checked in.
set -e
cd "$(dirname "$0")"
python3 - <<'PY'
import re, sys
cu = open('device_kernels.cu').read()
wgsl = open('device_kernels.wgsl').read()
names = re.findall(r'^DK_KERNEL\((dk_\w+)\)', cu, re.M)
entries = re.findall(r'^@compute[^\n]*\n\s*fn (\w+)\(', wgsl, re.M)
errors = []
table = []
for i, n in enumerate(names):
    m = re.match(r'dk_ewop_(\d+)$', n)
    if m:
        if 'dk_ew' not in entries: errors.append('no dk_ew entry point for ' + n)
        table.append((i, n, 'dk_ew', int(m.group(1))))
    else:
        if n not in entries: errors.append('no entry point for ' + n)
        table.append((i, n, n, -1))
for e in entries:
    if e.startswith('dk_') and e not in names: errors.append(e + ' is not a DK_KERNEL of device_kernels.cu')
for prefix in ('EW_', 'OPT_'):
    a = {k: int(v) for k, v in re.findall(r'^#define (' + prefix + r'\w+)\s+(\d+)', cu, re.M)}
    b = {k: int(v) for k, v in re.findall(r'^const (' + prefix + r'\w+) = (\d+);', wgsl, re.M)}
    if a != b: errors.append(prefix + '* codes differ: ' + str(sorted(set(a.items()) ^ set(b.items()))))
if errors:
    for e in errors: print('gen_device_kernels_wgsl: ' + e, file=sys.stderr)
    sys.exit(1)
out = ['// Generated by gen_device_kernels_wgsl.sh from device_kernels.wgsl -- do not edit.',
       '#pragma once', '', 'namespace std {', '',
       '// The WGSL entry point running DK_* kernel k (device_kernels.h\'s ids).',
       'static const char* device_kernel_wgsl_entry_(int k) {']
for i, n, e, op in table:
    out.append(f'    if (k == {i}) return "{e}";')
out.append('    return "";')
out.append('}')
out.append('')
out.append('// The pipeline constant OPC kernel k takes (dk_ewop_<op>: op), else -1.')
out.append('static int device_kernel_wgsl_opc_(int k) {')
for i, n, e, op in table:
    if op >= 0: out.append(f'    if (k == {i}) return {op};')
out.append('    return -1;')
out.append('}')
out.append('')
out.append('static const char* device_kernel_wgsl_source_() {')
out.append('    return')
for line in wgsl.split('\n'):
    esc = line.replace('\\', '\\\\').replace('"', '\\"')
    out.append(f'        "{esc}\\n"')
out[-1] = out[-1] + ';'
out.append('}')
out.append('')
out.append('} // namespace std')
open('device_kernels_wgsl.h', 'w').write('\n'.join(out) + '\n')
print(f'wrote device_kernels_wgsl.h ({len(names)} kernels, {len(entries)} entry points)')
PY
