#!/bin/sh
# Regenerates device_kernels.h (the kernel source as a string, and the
# kernel ids) and device_kernels_spirv.h (the kernels as SPIR-V, for
# device_vulkan.sc) from device_kernels.cu. Run after editing
# device_kernels.cu; both generated headers are checked in.
#
# The SPIR-V needs Slang's slangc (SLANGC=path, else on PATH; a release
# from github.com/shader-slang/slang) and SPIRV-Tools (spirv-val,
# spirv-dis, spirv-opt). Without slangc only device_kernels.h is
# regenerated, and device_vulkan.sc refuses to compile against the stale
# SPIR-V (the headers carry the source's CRC).
set -e
cd "$(dirname "$0")"
python3 - <<'PY'
import re, zlib
src = open('device_kernels.cu').read()
names = re.findall(r'^DK_KERNEL\((dk_\w+)\)', src, re.M)
out = ['// Generated by gen_device_kernels.sh from device_kernels.cu -- do not edit.',
       '#pragma once', '', 'namespace std {', '']
for i, n in enumerate(names):
    out.append(f'#define {n.upper()} {i}')
out.append(f'#define DK_COUNT {len(names)}')
out.append(f'#define DK_SOURCE_CRC 0x{zlib.crc32(src.encode()):08x}U')
out.append('')
ew=[(int(m.group(1)), n) for n in names for m in [re.match(r'dk_ewop_(\d+)$', n)] if m]
out.append('// The kernel running elementwise op code op alone (dk_ewop_<op>), or DK_EW.')
out.append('static int device_ew_kernel_(int op) {')
for c, n in ew:
    out.append(f'    if (op == {c}) return {n.upper()};')
out.append('    return DK_EW;')
out.append('}')
out.append('')
out.append('static const char* device_kernel_name_(int k) {')
for i, n in enumerate(names):
    out.append(f'    if (k == {i}) return "{n}";')
out.append('    return "";')
out.append('}')
out.append('')
out.append('static const char* device_kernel_source_() {')
out.append('    return')
for line in src.split('\n'):
    esc = line.replace('\\', '\\\\').replace('"', '\\"')
    out.append(f'        "{esc}\\n"')
out[-1] = out[-1] + ';'
out.append('}')
out.append('')
out.append('} // namespace std')
open('device_kernels.h', 'w').write('\n'.join(out) + '\n')
print(f'wrote device_kernels.h ({len(names)} kernels)')
PY

SLANGC="${SLANGC:-slangc}"
if ! command -v "$SLANGC" >/dev/null 2>&1; then
    echo "gen_device_kernels.sh: no slangc (set SLANGC): device_kernels_spirv.h not regenerated" >&2
    exit 0
fi
python3 - "$SLANGC" <<'PY'
# device_kernels.cu as Slang: the Vulkan prelude (DK_VULKAN) maps the
# portability layer, and the rewrites below the C++ spellings Slang lacks.
# Each kernel is its own SPIR-V module, per build: 0 plain, 1 DK_TAGGED
# (the DK_* kernels), 2 DK_ATTN64 and 3 both (the attention kernels).
import concurrent.futures, os, re, shutil, subprocess, sys, tempfile, zlib

def to_slang(s):
    # loops: clang's unroll pragma -> Slang's attribute
    s = re.sub(r'#pragma clang loop unroll\(full\)', '[unroll]', s)
    s = re.sub(r'_Pragma\("clang loop unroll\(full\)"\)', '[unroll]', s)
    # multi-word C types; 'ul' literals
    s = re.sub(r'\bunsigned\s+long\s+long\b', 'uint64_t', s)
    s = re.sub(r'\bunsigned\s+int\b', 'uint', s)
    s = re.sub(r'\bunsigned\s+short\b', 'uint16_t', s)
    s = re.sub(r'\bunsigned\s+char\b', 'uint8_t', s)
    s = re.sub(r'(\d)ul\b', r'\1ull', s)
    # templates -> generics: template <uint T, bool B = false> -> __generic<let T : uint, let B : bool = false>
    def tparams(m):
        out = []
        for p in m.group(1).split(','):
            mm = re.match(r'\s*(\w+)\s+(\w+)\s*(=\s*.+?)?\s*$', p)
            out.append(f'let {mm.group(2)} : {mm.group(1)}' + (f' {mm.group(3)}' if mm.group(3) else ''))
        return '__generic<' + ', '.join(out) + '>'
    s = re.sub(r'\btemplate\s*<([^<>]*)>', tparams, s)
    s = re.sub(r'\bconstexpr\b', 'static const', s)
    # threadgroup pointers -> TGPtr (an offset into the threadgroup array)
    s = re.sub(r'\bthreadgroup\s+float\s*\*\s*', 'TGPtr ', s)
    # references to arrays: thread T (&x)[A][B] -> inout T x[A][B]
    s = re.sub(r'(?:\bthread\s+)?(\w+)\s*\(\s*&\s*(\w+)\s*\)((?:\[[^\]]*\])+)', r'inout \1 \2\3', s)
    # trailing const on methods; const on pointer types (Slang's pointers are plain)
    s = re.sub(r'\)\s*const\s*\{', ') {', s)
    s = re.sub(r'\bconst\s+((?:dk_global|device)\s+)?(\w+)\s*\*', r'\1\2*', s)
    # parameters, in function headers: const T& x -> T x, T& x -> inout T x,
    # dk_shared T* x -> __ref T x[] (shared arrays), dk_thread T* x -> inout T x
    # (its function's *x and its callers' &y dropped)
    thread_ptr = {}
    def header(m):
        name, params, tail = m.group(1), m.group(2), m.group(3)
        if name in ('if', 'for', 'while', 'switch', 'return'):
            return m.group(0)
        ps = params.split(',')
        for i, p in enumerate(ps):
            q = re.sub(r'^(\s*)const\s+(?:constant\s+|dk_thread\s+|thread\s+)?([\w:]+)\s*&\s*', r'\1\2 ', p)
            q = re.sub(r'^(\s*)constant\s+([\w:]+)\s*&\s*', r'\1\2 ', q)
            q = re.sub(r'^(\s*)(?:dk_thread\s+|thread\s+)?([\w:]+)\s*&\s*(\w+)', r'\1inout \2 \3', q)
            q = re.sub(r'^(\s*)dk_shared\s+(\w+)\s*\*\s*(\w+)', r'\1__ref \2 \3[]', q)
            mm = re.match(r'^(\s*)dk_thread\s+(\w+)\s*\*\s*(\w+)', q)
            if mm:
                thread_ptr.setdefault(name, {})[i] = mm.group(3)
                q = f'{mm.group(1)}inout {mm.group(2)} {mm.group(3)}'
            ps[i] = q
        return f'{name}({",".join(ps)}){tail}'
    s = re.sub(r'\b(\w+)\s*\(([^()]*)\)(\s*\{)', header, s)
    for fn, idx in thread_ptr.items():
        m = re.search(r'\b' + fn + r'\s*\([^()]*\)\s*\{', s)
        depth, i = 0, m.end() - 1
        while True:
            depth += {'{': 1, '}': -1}.get(s[i], 0)
            i += 1
            if depth == 0:
                break
        body = s[m.end():i]
        for nm in idx.values():
            body = re.sub(r'\*\s*' + nm + r'\b', nm, body)
        s = s[:m.end()] + body + s[i:]
        def call(mc):
            args = mc.group(2).split(',')
            for k in idx:
                args[k] = re.sub(r'^(\s*)&', r'\1', args[k])
            return f'{mc.group(1)}({",".join(args)})'
        s = re.sub(r'\b(' + fn + r')\s*\(([^()]*)\)(?!\s*\{)', call, s)
    # the attention kernels' blocks are ATTN_T x ATTN_T threads
    s = re.sub(r'^DK_KERNEL\((dk_attn_\w+)\)', r'DK_ENTRY(\1, ATTN_T * ATTN_T)', s, flags=re.M)
    return s

# Threadgroup floats of a Metal-and-Vulkan kernel (DK_TG_FLOATS): the tiles its MK_GEMM / MK_CONV declares.
def tg_floats(name):
    m = re.match(r'mk_gemm(32|64)_', name)
    if m:
        return 2048
    m = re.match(r'mk_conv_(?:fwd|bwd_x|bwd_w)(32|64|w|s)_', name)
    if m:
        bm, bn = {'32': (32, 32), '64': (64, 64), 'w': (32, 128), 's': (8, 128)}[m.group(1)]
        return max(bm * 16, 8 * 64) + 16 * bn
    return 0

slangc = sys.argv[1]
src = open('device_kernels.cu').read()
crc = zlib.crc32(src.encode())
tmp = tempfile.mkdtemp(prefix='dkspirv')
sl = os.path.join(tmp, 'device_kernels.slang')
open(sl, 'w').write(to_slang(src))
base = [slangc, sl, '-target', 'spirv', '-profile', 'spirv_1_5', '-DDK_VULKAN', '-O3', '-fvk-use-entrypoint-name',
        '-warnings-disable', '30081,30051,41012']
# the entry points, from one module with all of them
allp = os.path.join(tmp, 'all.spv')
subprocess.run(base + ['-o', allp], check=True)
dis = subprocess.run(['spirv-dis', allp], capture_output=True, text=True, check=True).stdout
entries = re.findall(r'OpEntryPoint GLCompute %\w+ "(\w+)"', dis)
dk = [e for e in entries if e.startswith('dk_')]
attn = [e for e in dk if e.startswith('dk_attn_')]
jobs = [(0, e) for e in entries] + [(1, e) for e in dk] + [(2, e) for e in attn] + [(3, e) for e in attn]
defs = {0: [], 1: ['-DDK_TAGGED'], 2: ['-DDK_ATTN64'], 3: ['-DDK_TAGGED', '-DDK_ATTN64']}

def build(job):
    b, e = job
    out = os.path.join(tmp, f'{b}_{e}.spv')
    extra = [f'-DDK_TG_FLOATS={tg_floats(e)}'] if tg_floats(e) else []
    r = subprocess.run(base + defs[b] + extra + ['-entry', e, '-o', out], capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit(f'slangc failed on {e} (build {b}):\n{r.stderr}')
    subprocess.run(['spirv-opt', '--strip-debug', out, '-o', out], check=True)
    r = subprocess.run(['spirv-val', '--target-env', 'vulkan1.2', out], capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit(f'spirv-val rejects {e} (build {b}):\n{r.stdout}{r.stderr}')
    return open(out, 'rb').read()

with concurrent.futures.ThreadPoolExecutor(os.cpu_count() or 4) as ex:
    mods = list(ex.map(build, jobs))

ver = subprocess.run([slangc, '-v'], capture_output=True, text=True).stderr.strip() or '?'
words, index = [], []
for (b, e), m in zip(jobs, mods):
    index.append((b, len(words), len(m) // 4))
    words.extend(int.from_bytes(m[i:i + 4], 'little') for i in range(0, len(m), 4))
out = ['// Generated by gen_device_kernels.sh from device_kernels.cu (slangc ' + ver + ') -- do not edit.',
       '// Every kernel as a SPIR-V module, validated by spirv-val, per build: 0 plain,',
       '// 1 DK_TAGGED, 2 DK_ATTN64, 3 DK_TAGGED and DK_ATTN64.',
       '#pragma once', '',
       f'#define DK_SPIRV_SOURCE_CRC 0x{crc:08x}U',
       f'#define DK_SPIRV_MODULES {len(jobs)}', '', 'namespace std {', '',
       '// Module i: its entry point, build, first word and length in words.',
       'static const char* dk_spirv_name_(int i) {']
for i, (b, e) in enumerate(jobs):
    out.append(f'    if (i == {i}) return "{e}";')
out.append('    return "";')
out.append('}')
out.append(f'static const unsigned int dk_spirv_index_[{3 * len(jobs)}] = {{')
out.append(',\n'.join('    ' + ', '.join(f'{x}' for t in index[i:i + 6] for x in t) for i in range(0, len(index), 6)))
out.append('};')
out.append(f'static const unsigned int dk_spirv_words_[{len(words)}] = {{')
out.append(',\n'.join(','.join(str(w) for w in words[i:i + 16]) for i in range(0, len(words), 16)))
out.append('};')
out.append('')
out.append('} // namespace std')
open('device_kernels_spirv.h', 'w').write('\n'.join(out) + '\n')
shutil.rmtree(tmp)
print(f'wrote device_kernels_spirv.h ({len(jobs)} modules, {4 * len(words)} bytes of SPIR-V)')
PY
